/// 内置城市的小知识：经纬度、一句备注、一两句介绍、货币和电话区号。
///
/// 世界时钟面板城市名旁的“中国首都”、点开城市后的科普卡，日出日落按这里的
/// 经纬度离线算（`SunTimes`），天气也按它取。随 App 内置，不联网；中英两份
/// 直接写在表里，按界面语言取（`L10n.isEnglish`），不进 Localizable.xcstrings。
///
/// 写法：备注只说最稳妥的一点，拿不准的城市只写首都或国家；介绍一两句，只写
/// 地理和公认的地标，不写会过时的数字。货币写 ISO 4217 代码，区号写国际
/// 冠码后的国家或地区代码。表外的城市（系统时区）没有这些，界面不显示对应格子。
public struct CityFact: Equatable, Sendable {
    /// 和 `WorldCity.id` 一样。
    public var id: String
    public var latitude: Double
    public var longitude: Double
    /// ISO 4217，“USD”。
    public var currency: String
    /// “+1”“+852”。
    public var dialCode: String
    public var noteZh: String
    public var noteEn: String
    public var introZh: String
    public var introEn: String

    public init(id: String, latitude: Double, longitude: Double, currency: String, dialCode: String,
                noteZh: String, noteEn: String, introZh: String, introEn: String) {
        self.id = id
        self.latitude = latitude
        self.longitude = longitude
        self.currency = currency
        self.dialCode = dialCode
        self.noteZh = noteZh
        self.noteEn = noteEn
        self.introZh = introZh
        self.introEn = introEn
    }

    /// 城市名旁的短备注，当前界面语言。
    public var note: String { L10n.isEnglish ? noteEn : noteZh }
    /// 科普卡上的介绍，当前界面语言。
    public var intro: String { L10n.isEnglish ? introEn : introZh }
}

/// 货币的中英文名。
public struct CurrencyName: Equatable, Sendable {
    public var zh: String
    public var en: String
}

public enum CityFacts {
    /// 内置城市的小知识，按 id 查。
    public static func fact(id: String) -> CityFact? { byID[id] }

    /// 表外的城市（系统时区、手改的配置）是 nil。
    public static func fact(for city: WorldCity) -> CityFact? {
        city.isBuiltIn ? byID[city.id] : nil
    }

    /// 货币名，当前界面语言；表里没有时是代码本身。
    public static func currencyName(_ code: String) -> String {
        guard let name = currencies[code.uppercased()] else { return code.uppercased() }
        return L10n.isEnglish ? name.en : name.zh
    }

    private static let byID: [String: CityFact] = Dictionary(all.map { ($0.id, $0) },
                                                             uniquingKeysWith: { first, _ in first })

    private static func f(_ id: String, _ lat: Double, _ lon: Double, _ currency: String, _ dial: String,
                          _ noteZh: String, _ noteEn: String, _ introZh: String, _ introEn: String) -> CityFact {
        CityFact(id: id, latitude: lat, longitude: lon, currency: currency, dialCode: dial,
                 noteZh: noteZh, noteEn: noteEn, introZh: introZh, introEn: introEn)
    }

