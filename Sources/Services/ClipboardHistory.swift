import AppKit
import Observation

/// What has been copied lately, kept in memory and nowhere else.
///
/// The pasteboard has no change notification, so this watches its
/// `changeCount`, which is a cheap integer read, on a short poll gated by
/// `PollGate`. Only a change costs anything. Nothing is written to disk: the
/// history is gone when Docket quits, which is the only honest promise for
/// something that will inevitably catch a password now and then.
///
/// Password managers mark what they copy as concealed or transient
/// (nspasteboard.org's convention), and those entries are never recorded.
@MainActor @Observable
final class ClipboardHistory {
    static let shared = ClipboardHistory()

    struct Entry: Identifiable, Equatable {
        enum Content {
            case text(String)
            case image(NSImage, Data, NSPasteboard.PasteboardType)
            case files([URL])
        }

        let id = UUID()
        let content: Content
        let date: Date

        static func == (a: Entry, b: Entry) -> Bool { a.id == b.id }

        /// Whether two entries are the same copy, so copying it again moves
        /// it to the top rather than listing it twice.
        func same(as other: Entry) -> Bool {
            switch (content, other.content) {
            case (.text(let a), .text(let b)): a == b
            case (.image(_, let a, _), .image(_, let b, _)): a == b
            case (.files(let a), .files(let b)): a == b
            default: false
            }
        }

        var preview: String {
            switch content {
            case .text(let text):
                text.trimmingCharacters(in: .whitespacesAndNewlines)
                    .replacingOccurrences(of: "\n", with: " ")
            case .image(let image, _, _):
                "图片 \(Int(image.size.width))×\(Int(image.size.height))"
            case .files(let urls):
                urls.count == 1 ? urls[0].lastPathComponent : "\(urls.count) 个文件"
            }
        }
    }

    private(set) var entries: [Entry] = []

    static let limit = 20
    /// Large enough for a full screen capture, small enough that twenty of
    /// them stay a sensible amount of memory.
    private static let imageByteLimit = 24 * 1024 * 1024
    private static let textLimit = 20_000

    @ObservationIgnored private var timer: Timer?
    /// -1 so the first poll records whatever is on the pasteboard already.
    @ObservationIgnored private var lastChange = -1
    @ObservationIgnored private var lastCheck: Date = .distantPast

    private init() {}

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.8, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.3
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let now = Date.now
        guard PollGate.shouldStart(inFlight: false, blocked: false,
                                   sinceLastStart: now.timeIntervalSince(lastCheck),
                                   interval: 0.7) else { return }
        lastCheck = now
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard let entry = Self.read(board) else { return }
        entries = RecentList.inserting(entry, into: entries, limit: Self.limit) { $0.same(as: $1) }
    }

    private static let ignored: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    private static func read(_ board: NSPasteboard) -> Entry? {
        let types = board.types ?? []
        if types.contains(where: { ignored.contains($0.rawValue) }) { return nil }

        if types.contains(.fileURL),
           let urls = board.readObjects(forClasses: [NSURL.self],
                                        options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return Entry(content: .files(urls), date: .now)
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] where types.contains(type) {
            guard let data = board.data(forType: type), data.count <= imageByteLimit,
                  let image = NSImage(data: data) else { continue }
            return Entry(content: .image(image, data, type), date: .now)
        }
        if let text = board.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return Entry(content: .text(String(text.prefix(textLimit))), date: .now)
        }
        return nil
    }

    /// Puts an entry back on the pasteboard and moves it to the top.
    func copy(_ entry: Entry) {
        let board = NSPasteboard.general
        board.clearContents()
        switch entry.content {
        case .text(let text):
            board.setString(text, forType: .string)
        case .image(_, let data, let type):
            board.setData(data, forType: type)
        case .files(let urls):
            board.writeObjects(urls.map { $0 as NSURL })
        }
        // Our own write is not a new copy.
        lastChange = board.changeCount
        let moved = Entry(content: entry.content, date: .now)
        entries = RecentList.inserting(moved, into: entries.filter { $0.id != entry.id },
                                       limit: Self.limit) { $0.same(as: $1) }
    }

    /// Puts a starred text on the pasteboard, listing it as the newest copy.
    func copyText(_ text: String) {
        copy(Entry(content: .text(text), date: .now))
    }

    func remove(_ entry: Entry) {
        entries.removeAll { $0.id == entry.id }
    }

    func clear() {
        entries.removeAll()
    }
}
